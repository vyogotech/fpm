package archive

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"fpm/internal/metadata"
)

// TestNodeModulesAreNotPackaged: an app's node_modules (installed for the asset build)
// is a build-time input and must never end up in the archive, while the built
// output under <app>/public/dist must.
func TestNodeModulesAreNotPackaged(t *testing.T) {
	srcDir := buildTestApp(t, "node_app")
	for _, f := range []string{
		"node_modules/onscan.js/index.js",
		"node_app/public/node_modules/x.js",
		"node_app/public/dist/js/node_app.bundle.ABCDEFGH.js",
		"package.json",
	} {
		p := filepath.Join(srcDir, f)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte("x"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	outDir := t.TempDir()
	meta := &metadata.AppMetadata{PackageName: "node_app", AppName: "node_app", Org: "o", PackageVersion: "1.0.0", PackageType: "prod"}
	if err := CreateFPMArchive(srcDir, outDir, meta, "1.0.0"); err != nil {
		t.Fatalf("CreateFPMArchive: %v", err)
	}
	names, err := archiveEntryNames(filepath.Join(outDir, "node_app-1.0.0.fpm"))
	if err != nil {
		t.Fatal(err)
	}
	joined := strings.Join(names, "\n")
	if strings.Contains(joined, "node_modules") {
		t.Fatalf("node_modules must not be packaged; entries:\n%s", joined)
	}
	for _, want := range []string{"node_app/public/dist/js/node_app.bundle.ABCDEFGH.js", "package.json"} {
		if !strings.Contains(joined, want) {
			t.Fatalf("expected %s in archive; entries:\n%s", want, joined)
		}
	}
}
